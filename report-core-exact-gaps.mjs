#!/usr/bin/env node
/*
 * Emit the acquisition plan for the exact core-runtime assets.
 *
 * The core audit is deliberately fail-closed: it runs with the network disabled,
 * scans only local roots (npm cacache, pnpm store, package trees, and read-only
 * Docker containers), and rejects substitutes - other versions of the same
 * package, metadata, bundled host libraries and PLM plugins do not satisfy an
 * exact core reference. So the remaining gap cannot be closed by code; it needs
 * the authentic tarballs and, for the browser/platform gates, an authenticated
 * platform. This script turns the pinned inventory into the concrete work list
 * (what to obtain, where each package is referenced, how to verify it locally and
 * what each acceptance gate still needs) so the gap is actionable rather than a
 * paragraph of prose. It reads local files only: no network, no installs.
 *
 * Usage: node scripts/report-core-exact-gaps.mjs [--inventory PATH]
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const SCRIPT_DIR = dirname(fileURLToPath(import.meta.url));
const WORKSPACE = resolve(SCRIPT_DIR, '..');
// The status docs live in this repository (next to SOURCE-LOCALIZATION.md); the
// machine readable receipts stay with the other .artifacts data at the workspace root.
const DOC_PATH = join(SCRIPT_DIR, 'docs/core-exact-acquisition-plan.md');
const RECEIPT_PATH = join(WORKSPACE, '.artifacts/core-exact-acquisition-plan.json');
const DEFAULT_INVENTORY = join(
  WORKSPACE,
  '.artifacts/modeling-extension-inventory/continue-20260930-p1-pinned/inventory.json',
);

function parseArgs(argv) {
  const options = { inventory: DEFAULT_INVENTORY };
  for (let index = 0; index < argv.length; index += 1) {
    if (argv[index] === '--inventory') options.inventory = resolve(argv[++index]);
    else if (argv[index] === '--help') {
      console.log('Usage: node scripts/report-core-exact-gaps.mjs [--inventory PATH]');
      process.exit(0);
    } else {
      console.error(`unknown argument: ${argv[index]}`);
      process.exit(2);
    }
  }
  return options;
}

/** Register declared in an npmrc, when present; used only as a hint, never contacted. */
function declaredRegistry() {
  const npmrc = join(WORKSPACE, 'modelingweb/app/.npmrc');
  if (!existsSync(npmrc)) return null;
  const line = readFileSync(npmrc, 'utf8')
    .split('\n')
    .map(item => item.trim())
    .find(item => item.startsWith('registry='));
  return line ? line.slice('registry='.length) : null;
}

const { inventory } = parseArgs(process.argv.slice(2));
if (!existsSync(inventory)) {
  console.error(`inventory not found: ${inventory}`);
  console.error('Run the pinned extension inventory first; this script never fetches.');
  process.exit(2);
}

const data = JSON.parse(readFileSync(inventory, 'utf8'));
const core = data.coreRuntime ?? {};
const summary = data.summary ?? {};
const missing = core.missingExact ?? [];
const plugins = new Map((core.plugins ?? []).map(item => [item.repo, item]));
const registry = declaredRegistry();

const rows = missing.map(reference => {
  const at = reference.lastIndexOf('@');
  const name = reference.slice(0, at);
  const version = reference.slice(at + 1);
  const plugin = plugins.get(reference) ?? {};
  const references = (plugin.references ?? []).map(item => `${item.app}:${(item.locations ?? []).join(',')}`);
  return {
    reference,
    name,
    version,
    status: plugin.status ?? 'unknown',
    references,
    otherVersions: plugin.otherVersions ?? [],
    otherVersionsEligible: plugin.otherVersionsEligible ?? false,
    buildVerified: plugin.buildVerified ?? false,
    executionVerified: plugin.executionVerified ?? false,
  };
});

const gates = Object.entries(data.acceptanceCriteria ?? {}).map(([gate, meaning]) => ({ gate, meaning }));
const runtimeRequirements = data.coreRuntime?.summary
  ? ['exact-local-target-package', 'source-build-receipt', 'central-browser-verification',
    'model-design-browser-verification', 'zero-plugin-asset-404s', 'zero-unexplained-browser-errors']
  : [];

const lines = [];
lines.push('# Exact core-runtime asset gaps');
lines.push('');
lines.push('Generated by `node scripts/report-core-exact-gaps.mjs` from');
lines.push(`\`${inventory.replace(`${WORKSPACE}/`, '')}\` (inventory generated ${data.generatedAt}).`);
lines.push('This is a work list, not a status change: nothing here has been obtained or verified.');
lines.push('');
lines.push('## Counters as recorded in the pinned inventory');
lines.push('');
lines.push(`- \`coreExactRequested\`: ${summary.coreExactRequested} · \`coreExactComplete\`: ${summary.coreExactComplete} · \`coreExactMissing\`: ${summary.coreExactMissing}`);
lines.push(`- \`originalSourceCandidates\`: ${summary.originalSourceCandidates} (candidates, not authenticated sources) · \`originalExtensionsVerified\`: ${summary.originalExtensionsVerified}`);
lines.push(`- \`independentExtensionsVerified\`: ${summary.independentExtensionsVerified} · \`originalCompleteness\`: ${summary.originalCompleteness} · \`fullFlowVerified\`: ${summary.fullFlowVerified}`);
lines.push('');
lines.push('## 1. Exact runtime packages still missing');
lines.push('');
lines.push('| package@version | app reference | other versions seen locally | note |');
lines.push('|---|---|---|---|');
for (const row of rows) {
  const other = row.otherVersions.length ? row.otherVersions.join(', ') : 'none seen';
  lines.push(`| \`${row.reference}\` | ${row.references.join('; ') || 'unknown'} | ${other} | ${row.otherVersionsEligible ? 'eligible' : 'not eligible - a substitute does not count'} |`);
}
lines.push('');
lines.push(`Registry declared by \`modelingweb/app/.npmrc\`: ${registry ? `\`${registry}\`` : 'none found'}.`);
lines.push('Public npmjs.org and registry.npmmirror.com do not serve these package names at all,');
lines.push('and the internal registry above is only reachable from the intranet, so the tarballs');
lines.push('have to be obtained where that network is available and then verified locally.');
lines.push('');
lines.push('## 2. What each acceptance gate still needs');
lines.push('');
lines.push('The audit never awards a gate from a static inventory; unknown or unrun evidence fails closed.');
lines.push('');
for (const gate of gates) lines.push(`- **${gate.gate}** - ${gate.meaning}`);
lines.push('');
if (runtimeRequirements.length) {
  lines.push('Runtime requirements the core audit enumerates:');
  lines.push('');
  for (const item of runtimeRequirements) lines.push(`- \`${item}\``);
  lines.push('');
}
lines.push('## 3. Verification once the tarballs exist');
lines.push('');
lines.push('The audit finds exact packages by scanning local roots, so a legitimately obtained');
lines.push('tarball only has to reach one of them. No network is used by the audit itself.');
lines.push('');
lines.push('```sh');
lines.push('# from a directory that has the tarballs, e.g. obtained via the intranet registry');
lines.push('cd scripts');
lines.push('node harness-modeling-core-audit.mjs \\');
lines.push('  --npm-cache ~/.npm/_cacache \\');
lines.push('  --pnpm-store ~/.local/share/pnpm/store \\');
lines.push('  --directory ../vendor-upstream \\');
lines.push('  --container modelingweb');
lines.push('```');
lines.push('');
lines.push('Exit code 0 means every exact asset was found; 1 means gaps remain, 2 means the');
lines.push('audit itself was incomplete. Re-run `node scripts/report-core-exact-gaps.mjs`');
lines.push('afterwards to confirm this list is empty.');
lines.push('');
lines.push('## 4. What cannot be closed on a single workstation');
lines.push('');
lines.push('The `load`, `coreEdit`, `save`, `reload` and `platformIntegration` gates need an');
lines.push('authenticated platform session. In this workspace interactive login is not possible');
lines.push('for the vendor deployment either, because authentication delegates to the external');
lines.push('UAC/CAS endpoints (`cas.ibizcloud.cn`, `192.168.100.5`). Those gates therefore need');
lines.push('the same intranet access as the registry, not just the tarballs.');
lines.push('');
lines.push('Substitution is explicitly out of policy: other package versions, metadata, bundled');
lines.push('host libraries and PLM business plugins do not satisfy an exact core reference, so');
lines.push('this gap must stay open until the authentic assets and an authenticated platform are');
lines.push('available.');
lines.push('');

mkdirSync(dirname(DOC_PATH), { recursive: true });
mkdirSync(dirname(RECEIPT_PATH), { recursive: true });
writeFileSync(DOC_PATH, lines.join('\n'));
writeFileSync(
  RECEIPT_PATH,
  `${JSON.stringify({ generatedAt: new Date().toISOString(), inventory, registry, rows, gates, runtimeRequirements }, null, 2)}\n`,
);

console.log(`packages still missing : ${rows.length}`);
console.log(`acceptance gates        : ${gates.length}`);
console.log(`registry hint           : ${registry ?? '(none)'}`);
console.log(`wrote ${DOC_PATH.replace(`${WORKSPACE}/`, '')}`);
console.log(`wrote ${RECEIPT_PATH.replace(`${WORKSPACE}/`, '')}`);
